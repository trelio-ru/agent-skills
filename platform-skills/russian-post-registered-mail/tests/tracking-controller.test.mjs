import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import test from 'node:test';
import { runInNewContext } from 'node:vm';

const source = await readFile(new URL('../SKILL.md', import.meta.url), 'utf8');
const code = source.match(/```javascript\n(async function renameTrackingCard[\s\S]*?)\n```/u)?.[1];
assert.ok(code, 'The tested handler must be delivered in SKILL.md');
const rename = runInNewContext(`${code}\nrenameTrackingCard`, { URL });
const modulePath = process.env.POST_PLAYWRIGHT_MODULE;
const track = 'RA123456785RU';
const title = 'Желаемое название';

const trackingFixture = ({ storedTitle, signedOut, wrongTrack }) => `<!doctype html>
<meta charset="utf-8">
${signedOut ? '<a href="/api/auth/login">Войти</a>' : ''}
<form><input id="tracking-toolbar__search-input"></form>
<div id="tracking-card-portal" hidden>
  <div id="number"></div><span id="label"></span>
  ${signedOut ? '' : '<button id="tracking-card__rename-button">Edit</button>'}
  <input id="tracking-card__rename-input" hidden>
  <p>${title}</p>
</div>
<script>
  const search = document.querySelector('form');
  const card = document.getElementById('tracking-card-portal');
  const label = document.getElementById('label');
  const edit = document.getElementById('tracking-card__rename-button');
  const editor = document.getElementById('tracking-card__rename-input');
  const stored = ${JSON.stringify(storedTitle)};
  label.textContent = label.title = stored;
  search.addEventListener('submit', event => {
    event.preventDefault();
    document.getElementById('number').textContent =
      ${wrongTrack ? "'RB123456785RU'" : 'search.elements[0].value'};
    card.hidden = false;
  });
  edit?.addEventListener('click', () => {
    edit.hidden = true;
    editor.hidden = false;
    editor.value = label.title;
  });
  editor.addEventListener('keydown', event => {
    if (event.key !== 'Enter') return;
    label.textContent = label.title = editor.value; // Optimistic UI.
    editor.hidden = true;
    edit.hidden = false;
    fetch('/api/tracking/api/v1/trackings/title?track-number=' +
      encodeURIComponent(search.elements[0].value), {
        method: 'PUT', body: JSON.stringify({ title: editor.value }),
      }).catch(() => {});
  });
</script>`;

test('tracking command executes against a browser with no provider writes', {
  skip: !modulePath && 'Set POST_PLAYWRIGHT_MODULE to run the browser fixture',
}, async t => {
  const { chromium } = await import(pathToFileURL(modulePath).href);
  const browser = await chromium.launch({
    channel: process.platform === 'win32' ? 'msedge' : 'chrome', headless: true,
  });
  t.after(() => browser.close());

  async function fixture(t, { storedTitle = 'Старое название', signedOut, wrongTrack, save } = {}) {
    const context = await browser.newContext();
    t.after(() => context.close());
    const page = await context.newPage();
    const writes = [];
    let trackingLoads = 0;
    // Every request is intercepted; even the save generated by Enter stays local.
    await context.route('**/*', async route => {
      const request = route.request();
      const url = new URL(request.url());
      if (url.origin !== 'https://www.pochta.ru') return route.abort();
      if (url.pathname === '/account') return route.fulfill({ body: '<p>Account</p>' });
      if (url.pathname === '/tracking') {
        trackingLoads += 1;
        return route.fulfill({
          contentType: 'text/html',
          body: trackingFixture({ storedTitle, signedOut, wrongTrack }),
        });
      }
      if (request.method() === 'PUT' && url.pathname === '/api/tracking/api/v1/trackings/title') {
        const body = request.postDataJSON();
        writes.push({ track: url.searchParams.get('track-number'), ...body });
        if (save !== 'lost_without_write') storedTitle = body.title;
        if (save) return route.abort();
        return route.fulfill({ status: 200, body: '{}' });
      }
      return route.abort();
    });
    await page.goto('https://www.pochta.ru/account');
    return { page, writes, loads: () => trackingLoads };
  }

  await t.test('goes straight from account, saves the exact card once, then reloads', async t => {
    const { page, writes, loads } = await fixture(t);
    assert.equal((await rename(page, { track, title })).state, 'saved');
    assert.deepEqual(writes, [{ track, title }]);
    assert.equal(loads(), 2);
  });

  await t.test('checks a matching name after reload without a write', async t => {
    const { page, writes, loads } = await fixture(t, { storedTitle: title });
    assert.equal((await rename(page, { track, title })).state, 'match');
    assert.equal(loads(), 2);
    assert.deepEqual(writes, []);
  });

  await t.test('requires login only when tracking shows the login control', async t => {
    const { page, writes } = await fixture(t, { signedOut: true });
    assert.equal((await rename(page, { track, title })).state, 'login_required');
    assert.deepEqual(writes, []);
  });

  await t.test('refuses another card even when its text contains the wanted title', async t => {
    const { page, writes } = await fixture(t, { wrongTrack: true });
    assert.equal((await rename(page, { track, title })).state, 'tracking_control_unavailable');
    assert.deepEqual(writes, []);
  });

  await t.test('reconciles a lost reply by reloading and verifying the persisted title', async t => {
    const { page, writes } = await fixture(t, { save: 'lost_after_write' });
    assert.equal((await rename(page, { track, title })).state, 'saved');
    assert.deepEqual(writes, [{ track, title }]);
  });

  await t.test('leaves an unverified save open and verifyOnly never writes', async t => {
    const { page, writes } = await fixture(t, { save: 'lost_without_write' });
    assert.equal((await rename(page, { track, title })).state, 'save_unverified');
    assert.equal((await rename(page, { track, title, verifyOnly: true })).state, 'different');
    assert.deepEqual(writes, [{ track, title }]);
  });
});
