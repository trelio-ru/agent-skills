import fs from 'node:fs/promises';
import { stripTypeScriptTypes } from 'node:module';

// Keep the existing Playwright 1.60 storage format without calling its page-
// creating storageState APIs. The reviewed upstream TypeScript and its license
// are checked in; building is offline and never evaluates the browser script.
// Git on Windows can check text files out as CRLF. Compare the canonical text,
// not a checkout's line endings, and always generate the same LF artifact.
const readText = async url => (await fs.readFile(url, 'utf8')).replace(/\r\n/g, '\n');
const source = async name => {
  const input = await readText(new URL(`vendor/playwright/${name}.ts`, import.meta.url));
  const stripped = stripTypeScriptTypes(input, { mode: 'strip' })
    .replace(/^import .*;\s*$/gm, '').replace(/^export /gm, '');
  return stripped.split('\n').map(line => line.trimEnd()).join('\n').replace(/\n{3,}/g, '\n\n').trim();
};
const output = `// Generated by development/build-storage-codec.mjs; do not edit.\n` +
  `// Playwright 1.60.0, Copyright Microsoft Corporation, Apache-2.0.\n` +
  `// See playwright-storage-LICENSE.txt and development/vendor/playwright.\n` +
  `export async function storageCodec({ mode, state }) {\n` +
  `${await source('utilityScriptSerializers')}\n${await source('storageScript')}\n` +
  `const script = new StorageScript(false);\n` +
  `if (mode === 'restore') return script.restore(state);\n` +
  `if (mode === 'collect') return script.collect(true);\n` +
  `throw new Error('storage_codec_operation_rejected');\n}\n`;
const target = new URL('../scripts/storage-codec.mjs', import.meta.url);
const license = await readText(new URL('vendor/playwright/LICENSE', import.meta.url));
const licenseTarget = new URL('../scripts/playwright-storage-LICENSE.txt', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readText(target) !== output || await readText(licenseTarget) !== license)
    throw new Error('storage_codec_rebuild_required');
} else {
  await fs.writeFile(target, output);
  await fs.writeFile(licenseTarget, license);
}
